using GEvolve.Engine.World.LandmassGeneration.Shared;
using GEvolve.State.Game;

namespace GEvolve.Engine.World.LandmassGeneration;

/// <summary>A cortical identity is not a tectonic plate ID, a land component, or an elevation.</summary>
public readonly record struct CorticalFragment(int Id, int CoreCellId);

/// <summary>Each province belongs to one fragment and occupies a connected set of continental hexes.</summary>
public readonly record struct CorticalProvince(int Id, int FragmentId, int CoreCellId);

public enum CorticalAssemblyKind : byte { Accreted, RiftSeparated }

/// <summary>A geological relationship; it does not connect land or change a surface mask.</summary>
public readonly record struct CorticalAssemblyLink(int FirstFragmentId, int SecondFragmentId,
    CorticalAssemblyKind Kind);

/// <summary>
/// H05-A1 shared, non-persisted input/output contract for distinct world strategies.
/// -1 means no continental fragment/province (oceanic crust). IDs index the respective
/// descriptor arrays and are independent of the universal 16 plate IDs.
/// Emergence affinity is a finite relative score, not land/ocean or height.
/// No surface, sea level, or relief is generated by this record.
/// </summary>
public sealed record SharedCorticalModel(string Version, byte[] CrustByCellId,
    int[] FragmentByCellId, int[] ProvinceByCellId,
    float[] EmergenceAffinityByCellId, CorticalFragment[] Fragments,
    CorticalProvince[] Provinces, CorticalAssemblyLink[] AssemblyLinks)
{
    public const string CurrentVersion = "shared-cortex-1";
}

/// <summary>Checks structural references and province topology, without choosing a world profile.</summary>
public static class SharedCorticalModelValidator
{
    private static bool ContainsInvalidPlate(ReadOnlySpan<byte> ids)
    {
        foreach (byte id in ids) if (id >= 16) return true;
        return false;
    }

    private static bool ContainsInvalidSurface(ReadOnlySpan<byte> ids)
    {
        foreach (byte id in ids) if (id is not (0 or 1)) return true;
        return false;
    }

    public static void Validate(HexTopology topology, SharedCorticalModel model,
        ReadOnlySpan<byte> plateByCellId, ReadOnlySpan<byte> surfaceByCellId = default)
    {
        ArgumentNullException.ThrowIfNull(topology);
        ArgumentNullException.ThrowIfNull(model);
        int count = topology.Count;
        if (model.Version != SharedCorticalModel.CurrentVersion ||
            model.CrustByCellId is null || model.CrustByCellId.Length != count ||
            model.FragmentByCellId is null || model.FragmentByCellId.Length != count ||
            model.ProvinceByCellId is null || model.ProvinceByCellId.Length != count ||
            model.EmergenceAffinityByCellId is null || model.EmergenceAffinityByCellId.Length != count ||
            model.Fragments is null || model.Provinces is null || model.AssemblyLinks is null ||
            plateByCellId.Length != count ||
            ContainsInvalidPlate(plateByCellId) ||
            (!surfaceByCellId.IsEmpty && (surfaceByCellId.Length != count ||
                ContainsInvalidSurface(surfaceByCellId))))
            throw new ArgumentException("Invalid cortical model dimensions, version or plate/surface input.");

        var fragmentCounts = new int[model.Fragments.Length];
        var provinceCounts = new int[model.Provinces.Length];
        for (int id = 0; id < count; id++)
        {
            byte crust = model.CrustByCellId[id];
            int fragment = model.FragmentByCellId[id], province = model.ProvinceByCellId[id];
            if (!float.IsFinite(model.EmergenceAffinityByCellId[id]) ||
                (crust != (byte)CrustKind.Oceanic && crust != (byte)CrustKind.Continental))
                throw new ArgumentException("Invalid crust kind or emergence affinity.");
            if (crust == (byte)CrustKind.Oceanic)
            {
                if (fragment != -1 || province != -1)
                    throw new ArgumentException("Oceanic crust cannot reference continental fragments.");
                continue;
            }
            if ((uint)fragment >= (uint)fragmentCounts.Length ||
                (uint)province >= (uint)provinceCounts.Length ||
                model.Provinces[province].FragmentId != fragment)
                throw new ArgumentException("Continental crust references an invalid fragment or province.");
            fragmentCounts[fragment]++;
            provinceCounts[province]++;
        }

        for (int id = 0; id < model.Fragments.Length; id++)
        {
            var fragment = model.Fragments[id];
            if (fragment.Id != id || fragmentCounts[id] == 0 ||
                (uint)fragment.CoreCellId >= (uint)count ||
                model.FragmentByCellId[fragment.CoreCellId] != id)
                throw new ArgumentException("Fragment is empty, misidentified or has an invalid core.");
        }
        for (int id = 0; id < model.Provinces.Length; id++)
        {
            var province = model.Provinces[id];
            if (province.Id != id || provinceCounts[id] == 0 ||
                (uint)province.FragmentId >= (uint)model.Fragments.Length ||
                (uint)province.CoreCellId >= (uint)count ||
                model.ProvinceByCellId[province.CoreCellId] != id ||
                model.FragmentByCellId[province.CoreCellId] != province.FragmentId)
                throw new ArgumentException("Province is empty, misidentified or has an invalid core.");
        }

        // An individual province is connected by actual cylinder topology (E/W wraps, N/S does not).
        var visited = new int[count];
        var queue = new int[count];
        for (int province = 0; province < provinceCounts.Length; province++)
        {
            int head = 0, tail = 0, core = model.Provinces[province].CoreCellId;
            int stamp = province + 1;
            queue[tail++] = core;
            visited[core] = stamp;
            while (head < tail)
            {
                foreach (int neighbor in topology.Neighbors(queue[head++]))
                    if (visited[neighbor] != stamp && model.ProvinceByCellId[neighbor] == province)
                    {
                        visited[neighbor] = stamp;
                        queue[tail++] = neighbor;
                    }
            }
            if (tail != provinceCounts[province])
                throw new ArgumentException("Province has disconnected hexagonal components.");
        }

        var pairs = new HashSet<(int, int)>();
        foreach (var link in model.AssemblyLinks)
        {
            if ((uint)link.FirstFragmentId >= (uint)fragmentCounts.Length ||
                (uint)link.SecondFragmentId >= (uint)fragmentCounts.Length ||
                link.FirstFragmentId >= link.SecondFragmentId ||
                !Enum.IsDefined(link.Kind) ||
                !pairs.Add((link.FirstFragmentId, link.SecondFragmentId)))
                throw new ArgumentException("Invalid, duplicate or noncanonical assembly relationship.");
        }
    }
}
